namespace Maroik.Core.Service.Services;

/// <summary>
/// Implementation of <see cref="IAccountRegistrationService"/>: self-registration and the e-mail confirmation.
/// Data Protection (<see cref="IDataProtectionService"/>) protects the token embedded in the confirmation link, which is
/// generated by <see cref="GuidToken"/>. Email bodies are built via <see cref="IMailClient"/> and handed off to
/// <see cref="IEmailPublisher"/>, which enqueues them for asynchronous SMTP delivery by Maroik.Worker instead of sending inline.
/// </summary>
public class AccountRegistrationService(
    IAccountRepository accountRepository,
    IPasswordService passwordService,
    IMailClient mailClient,
    IEmailPublisher emailPublisher,
    IOptions<ServerSetting> settings,
    IDataProtectionService dataProtection,
    ILogger<AccountRegistrationService> logger,
    IUnitOfWork unitOfWork,
    TimeProvider timeProvider
    ) : IAccountRegistrationService
{
    /// <inheritdoc />
    public async Task<RegisterResult> RegisterAsync(RegisterAccountRequest newAccount, EmailTemplate emailTemplate, CancellationToken ct = default)
    {
        DateTime utcNow = timeProvider.GetUtcNow().UtcDateTime;
        // The existence check uses the form Account.Create stores (trimmed, lower-case).
        Account? existing = await accountRepository.FindByEmailAsync(Email.NormalizeForLookup(newAccount.Email), ct);

        if (existing == null)
            return await RegisterNewAccountAsync(newAccount, emailTemplate, utcNow, ct);

        return existing.EmailConfirmed
            ? await AnswerAlreadyConfirmedRegistrationAsync(existing, newAccount, utcNow, ct)
            : await ReplaceUnconfirmedRegistrationAsync(existing, newAccount, emailTemplate, utcNow, ct);
    }

    /// <summary>A registration for an address no account has: creates the account and mails its confirmation link.</summary>
    private async Task<RegisterResult> RegisterNewAccountAsync(RegisterAccountRequest newAccount, EmailTemplate emailTemplate, DateTime utcNow, CancellationToken ct)
    {
        if (Account.RequireServiceTermsForRegistration(newAccount.AgreedServiceTerms) is { IsError: true } noConsent)
            return RegisterResult.FromError(noConsent.FirstError);

        // Validate + normalize the nickname first (cheap, and before the deliberately slow
        // BCrypt hash below). The reserved-name rule applies here: self-registration may not
        // claim a staff / system name. Uniqueness is checked ignoring case, since the database
        // constraint alone is case-sensitive and would let "bob" register next to "Bob".
        var nicknameResult = NicknamePolicy.Validate(newAccount.Nickname);
        if (nicknameResult.IsError)
            return RegisterResult.FromError(nicknameResult.FirstError);
        string nickname = nicknameResult.Value;

        if (await accountRepository.NicknameExistsIgnoreCaseAsync(nickname, ct))
            return RegisterResult.Fail(ServiceErrorKeys.NicknameExists, errorArgs: [nickname]);

        // Enforce the password-complexity rule at the service boundary (not just the ViewModel),
        // before hashing — Account.Create only ever sees the already-hashed value.
        if (!PasswordPolicy.IsValid(newAccount.PlainPassword))
            return RegisterResult.Fail(PasswordPolicy.ViolationMessage);

        // Brand-new account: hash the plain-text password and create the domain entity.
        string hashedPassword = passwordService.HashPassword(newAccount.PlainPassword ?? "");

        // Self-registration always creates a plain User account; the request has no way to
        // choose a role or any admin-only state, and the confirmation token is generated here.
        // The account keeps only its hash; the token itself goes out in the mail below.
        string registrationToken = GuidToken.Generate(utcNow);
        var createResult = Account.Create(
            newAccount.Email ?? "",
            hashedPassword,
            nickname,
            AccountRole.User,
            newAccount.TimeZoneIanaId ?? "UTC",
            defaultMonetaryUnit: null,
            registrationToken,
            newAccount.AgreedServiceTerms, utcNow);

        if (createResult.IsError)
            return RegisterResult.FromError(createResult.FirstError);

        var account = createResult.Value;
        account.SetMessage(AccountMessage.UserCreatedVerifyEmail.GetDescription(), utcNow);

        try
        {
            await accountRepository.CreateAsync(account, ct);
        }
        catch (DuplicateKeyException e)
        {
            // The prior FindByEmailAsync check above is a read-then-write race: two concurrent
            // registrations for the same not-yet-registered email or nickname can both pass it.
            // Report whichever one actually collided instead of always blaming the nickname.
            return e.Key == DuplicateKey.AccountNickname
                ? RegisterResult.Fail(ServiceErrorKeys.NicknameExists, errorArgs: [nickname])
                : RegisterResult.Fail(ServiceErrorKeys.EmailExists, errorArgs: [newAccount.Email ?? ""]);
        }
        catch (Exception e)
        {
            logger.LogError(e, "Failed to create account for {Email}", newAccount.Email);
            return RegisterResult.Fail(ServiceErrorKeys.RegistrationFailed);
        }

        logger.LogInformation("Account registered: {Email}", account.Email.Value);

        // The account was just created with UserCreatedVerifyEmail already set above, so a
        // successful send should not overwrite it with VerifyEmail.
        return await SendConfirmationEmailAndUpdateStatusAsync(
            account, registrationToken, emailTemplate,
            setVerifyEmailMessageOnSuccess: false, repeat: false, utcNow, ct);
    }

    /// <summary>A registration for an address nobody has confirmed yet: replaces the earlier registrant's credentials and mails a new link.</summary>
    private async Task<RegisterResult> ReplaceUnconfirmedRegistrationAsync(Account existing, RegisterAccountRequest newAccount, EmailTemplate emailTemplate, DateTime utcNow, CancellationToken ct)
    {
        if (Account.RequireServiceTermsForRegistration(newAccount.AgreedServiceTerms) is { IsError: true } noConsent)
            return RegisterResult.FromError(noConsent.FirstError);

        // Pre-hijacking guard: nobody has proven they own this address yet, so this submission
        // REPLACES the earlier registrant's password / nickname / time zone instead of just
        // re-mailing a link for credentials someone else chose. Together with ConfirmEmailAsync
        // requiring the registration password, the account only ever activates for the person
        // holding both the mailbox and the password. Input is validated and hashed before the
        // lock, so the BCrypt cost is never paid while holding it.
        var nicknameResult = NicknamePolicy.Validate(newAccount.Nickname);
        if (nicknameResult.IsError)
            return RegisterResult.FromError(nicknameResult.FirstError);
        string nickname = nicknameResult.Value;

        if (!PasswordPolicy.IsValid(newAccount.PlainPassword))
            return RegisterResult.Fail(PasswordPolicy.ViolationMessage);

        string hashedPassword = passwordService.HashPassword(newAccount.PlainPassword ?? "");
        string registrationToken = GuidToken.Generate(utcNow);

        Account locked;
        await unitOfWork.BeginAsync(ct: ct);
        try
        {
            // Re-read under FOR UPDATE: serializes against a concurrent ConfirmEmailAsync /
            // ResendConfirmationEmailAsync write to the same row, so this cannot overwrite an
            // account a concurrent confirm just activated. The lock is released at Commit below,
            // before the network mail send that follows.
            Account? found = await accountRepository.FindByEmailForUpdateAsync(existing.Email.Value, ct);
            if (found == null)
            {
                await unitOfWork.RollbackAsync(ct);
                return RegisterResult.Fail(ServiceErrorKeys.RegistrationFailed);
            }

            if (found.EmailConfirmed)
            {
                // Confirmed by a concurrent request while this one waited for the lock.
                await unitOfWork.RollbackAsync(ct);
                return RegisterResult.Fail(AccountMessage.UserAlreadyCreated.GetDescription());
            }

            if (found.Deleted)
            {
                // Not re-registrable. It answers like a confirmed address, deleted or not: the deletion is only
                // disclosed to a caller who proved the password (at sign-in).
                await unitOfWork.RollbackAsync(ct);
                logger.LogWarning("Registration refused: the account is deleted for {Email}", found.Email.Value);
                return RegisterResult.Fail(AccountMessage.UserAlreadyCreated.GetDescription());
            }

            // The account's own nickname (in any letter case) is not a conflict — only another
            // account holding it is. The case-insensitive unique index still backstops a race.
            if (!string.Equals(found.Nickname, nickname, StringComparison.OrdinalIgnoreCase)
                && await accountRepository.NicknameExistsIgnoreCaseAsync(nickname, ct))
            {
                await unitOfWork.RollbackAsync(ct);
                return RegisterResult.Fail(ServiceErrorKeys.NicknameExists, errorArgs: [nickname]);
            }

            // A fresh token always: every link mailed for the replaced registration dies with it.
            var replaceResult = found.ReplaceUnconfirmedRegistration(
                hashedPassword, nickname, newAccount.TimeZoneIanaId ?? "UTC", registrationToken, newAccount.AgreedServiceTerms, utcNow);
            if (replaceResult.IsError)
            {
                await unitOfWork.RollbackAsync(ct);
                return RegisterResult.FromError(replaceResult.FirstError);
            }

            await accountRepository.UpdateEntityAsync(found, ct);
            await unitOfWork.CommitAsync(ct);
            locked = found;
        }
        catch (DuplicateKeyException e) when (e.Key == DuplicateKey.AccountNickname)
        {
            // Another registration took the nickname between the check above and the commit.
            await unitOfWork.RollbackAsync(ct);
            return RegisterResult.Fail(ServiceErrorKeys.NicknameExists, errorArgs: [nickname]);
        }
        catch
        {
            await unitOfWork.RollbackAsync(ct);
            throw;
        }

        logger.LogInformation("Unconfirmed registration replaced for {Email}", locked.Email.Value);

        // Mail send + final status write run unlocked, after the row lock above was released.
        // SendConfirmationEmailAndUpdateStatusAsync re-persists the same token hash it finds on
        // `locked` as its first step — a harmless idempotent re-write of the value just
        // committed above — then sends the mail and writes the final status column, none of
        // which need this row's lock held.
        return await SendConfirmationEmailAndUpdateStatusAsync(
            locked, registrationToken, emailTemplate,
            setVerifyEmailMessageOnSuccess: true, repeat: false, utcNow, ct);
    }

    /// <summary>A registration for a confirmed address: answers "already exists", reconciling the account's status only for its proven owner.</summary>
    private async Task<RegisterResult> AnswerAlreadyConfirmedRegistrationAsync(Account existing, RegisterAccountRequest newAccount, DateTime utcNow, CancellationToken ct)
    {
        // Account is fully confirmed: tell the caller it already exists and bring the account's own
        // stored status into line — but write a column only when its value would actually change.
        // This path runs off an un-locked FindByEmailAsync read against another user's row from an
        // unauthenticated request, so it must NOT use the full-row UpdateEntityAsync (it would
        // revert a concurrent self-service change from the stale snapshot), and a no-op must stay a
        // no-op: an email-enumerating caller must not be able to churn a stranger's Updated
        // timestamp by replaying this endpoint. Column-scoped writes only, like every other Account
        // write path.
        //
        // Ownership gate: knowing the address is not enough to mutate the row. Only when the caller
        // also supplies the account's current password (the legit owner re-running registration to
        // recover a legacy "confirmed but terms not accepted" state) do we reconcile
        // AgreedServiceTerms / Message — otherwise anyone who knows a registered address could flip
        // another account's terms flag or status message. The BCrypt verify also keeps this path's
        // cost in line with the new-account path (which hashes) so the "already exists" outcome is
        // not distinguishable by timing.
        string alreadyCreatedMessage = AccountMessage.UserAlreadyCreated.GetDescription();
        bool callerOwnsAccount =
            passwordService.VerifyPassword(newAccount.PlainPassword ?? "", existing.HashedPassword);
        if (!callerOwnsAccount)
        {
            return RegisterResult.Fail(alreadyCreatedMessage);
        }

        try
        {
            if (!existing.AgreedServiceTerms)
            {
                existing.AcceptServiceTerms(utcNow);
                await accountRepository.UpdateAgreedServiceTermsAsync(
                    existing.Email.Value, existing.AgreedServiceTerms, existing.Updated, ct);
            }

            if (!string.Equals(existing.Message, alreadyCreatedMessage, StringComparison.Ordinal))
            {
                existing.SetMessage(alreadyCreatedMessage, utcNow);
                await accountRepository.UpdateMessageAsync(
                    existing.Email.Value, existing.Message, existing.Updated, ct);
            }
        }
        catch (Exception e)
        {
            logger.LogError(e, "Failed to update account status for {Email}", existing.Email.Value);
            return RegisterResult.Fail(ServiceErrorKeys.AccountStatusFailed);
        }

        return RegisterResult.Fail(alreadyCreatedMessage);
    }

    /// <inheritdoc />
    public async Task<RegisterResult> ResendConfirmationEmailAsync(string email, EmailTemplate emailTemplate, CancellationToken ct = default)
    {
        DateTime utcNow = timeProvider.GetUtcNow().UtcDateTime;
        email = Email.NormalizeForLookup(email);
        Account? account = await accountRepository.FindByEmailAsync(email, ct);
        if (account == null)
            return RegisterResult.Fail(ServiceErrorKeys.ResendEmailFailed, showResendEmail: true);

        if (account.EmailConfirmed)
        {
            // Email is already confirmed: just inform the caller. This request has no proof of
            // ownership (unlike RegisterAsync's equivalent branch, which requires the account's
            // password before writing anything) -- an unauthenticated caller who only knows the
            // address must not be able to mutate the account, so this path is read-only.
            return RegisterResult.Fail(AccountMessage.UserAlreadyCreated.GetDescription());
        }

        string registrationToken = GuidToken.Generate(utcNow);
        Account locked;
        await unitOfWork.BeginAsync(ct: ct);
        try
        {
            // Re-read under FOR UPDATE before regenerating/persisting the token: serializes against
            // a concurrent ConfirmEmailAsync/RegisterAsync write to the same row (both take the
            // same lock before writing) so this cannot resurrect a token a concurrent confirm just
            // consumed, or vice versa. The lock is held only long enough to persist the
            // regenerated token's hash — released at Commit below, before the network mail send
            // that follows, so a slow/degraded broker cannot hold this row's lock (and this
            // request's DB connection) open for the duration of the publish.
            Account? found = await accountRepository.FindByEmailForUpdateAsync(email, ct);
            if (found == null)
            {
                await unitOfWork.RollbackAsync(ct);
                return RegisterResult.Fail(ServiceErrorKeys.ResendEmailFailed, showResendEmail: true);
            }

            if (found.EmailConfirmed)
            {
                // Confirmed by a concurrent request while this one waited for the lock.
                await unitOfWork.RollbackAsync(ct);
                return RegisterResult.Fail(AccountMessage.UserAlreadyCreated.GetDescription());
            }

            if (found.Deleted)
            {
                // No mail for a deleted account. It answers like the registration does, without disclosing the deletion.
                await unitOfWork.RollbackAsync(ct);
                logger.LogWarning("Confirmation resend refused: the account is deleted for {Email}", found.Email.Value);
                return RegisterResult.Fail(AccountMessage.UserAlreadyCreated.GetDescription());
            }

            // A fresh token on every resend: the row keeps only the earlier token's hash, so that
            // token cannot be mailed again. The links of earlier mails stop working.
            found.RegenerateRegistrationToken(registrationToken, utcNow);

            await accountRepository.UpdateRegistrationTokenAsync(found.Email.Value, found.RegistrationToken, found.Updated, ct);
            await unitOfWork.CommitAsync(ct);
            locked = found;
        }
        catch
        {
            await unitOfWork.RollbackAsync(ct);
            throw;
        }

        // Mail send + final status write run unlocked, after the row lock above was released.
        // repeat: true signals the UI that this is a resend, not the first confirmation.
        return await SendConfirmationEmailAndUpdateStatusAsync(
            locked, registrationToken, emailTemplate,
            setVerifyEmailMessageOnSuccess: true, repeat: true, utcNow, ct);
    }

    /// <summary>The token inside a confirmation link's protected value, or <see langword="null"/> (logged) when the value does not decrypt.</summary>
    private string? TryUnprotectRegistrationToken(string encryptedToken)
    {
        try { return dataProtection.Unprotect(ProtectedValue.MailToken, encryptedToken); }
        catch (Exception e)
        {
            logger.LogWarning(e, "Failed to decrypt registration token");
            return null;
        }
    }

    /// <inheritdoc />
    public async Task<ConfirmEmailResult> ValidateRegistrationTokenAsync(string encryptedToken, CancellationToken ct = default)
    {
        DateTime utcNow = timeProvider.GetUtcNow().UtcDateTime;
        if (TryUnprotectRegistrationToken(encryptedToken) is not { } rawToken)
            return new ConfirmEmailResult { InvalidToken = true, AccountCreated = false };

        Account? account = await FindByRegistrationTokenAsync(rawToken, ct);
        // A live link: show the password form, echoing the still-encrypted token back into it.
        if (account is { Deleted: false } && GuidToken.IsTokenAlive(rawToken, utcNow))
            return new ConfirmEmailResult
            {
                InvalidToken = false, AccountCreated = false, RegistrationToken = encryptedToken
            };
        logger.LogWarning("Email confirmation link rejected: invalid or expired token");
        return new ConfirmEmailResult { InvalidToken = true, AccountCreated = false };
    }

    /// <inheritdoc />
    public async Task<ConfirmEmailResult> ConfirmEmailAsync(string encryptedToken, string password, CancellationToken ct = default)
    {
        DateTime utcNow = timeProvider.GetUtcNow().UtcDateTime;
        if (TryUnprotectRegistrationToken(encryptedToken) is not { } rawToken)
            return InvalidConfirmationToken();

        Account? account = await FindByRegistrationTokenAsync(rawToken, ct);
        if (account == null)
        {
            logger.LogWarning("Email confirmation rejected: invalid or expired token");
            return InvalidConfirmationToken();
        }

        // Reject tokens that have passed their time-to-live window.
        if (!GuidToken.IsTokenAlive(rawToken, utcNow))
        {
            logger.LogWarning("Email confirmation rejected: invalid or expired token for {Email}", account.Email.Value);
            return InvalidConfirmationToken();
        }

        await unitOfWork.BeginAsync(ct: ct);
        try
        {
            // Re-read under FOR UPDATE, serializing against a concurrent ResendConfirmationEmailAsync
            // / RegisterAsync write to the same row (both take the same lock before writing) so
            // this confirm cannot act on a registration-token snapshot a concurrent resend has
            // already superseded, or vice versa.
            Account? locked = await accountRepository.FindByEmailForUpdateAsync(account.Email.Value, ct);
            if (locked == null)
            {
                await unitOfWork.RollbackAsync(ct);
                logger.LogWarning("Email confirmation rejected: invalid or expired token for {Email}", account.Email.Value);
                return InvalidConfirmationToken();
            }

            // ConfirmEmail enforces its own invariant against the freshly-locked row: it rejects a
            // token that no longer matches RegistrationToken (superseded by a concurrent resend) the
            // same way it rejects any other invalid token, and separately reports Conflict when the
            // locked row is already confirmed.
            // The link proves the mailbox; the registration password proves the credentials. Both must
            // belong to the same person, otherwise someone who pre-registered this address could have
            // its owner activate an account with the pre-registrant's password. Checked against the
            // locked row — the credentials actually being activated. An already-confirmed row skips
            // this and falls through to ConfirmEmail's "already confirmed" answer.
            if (!locked.EmailConfirmed && !passwordService.VerifyPassword(password, locked.HashedPassword))
            {
                await unitOfWork.RollbackAsync(ct);
                logger.LogWarning("Email confirmation refused: password does not match the registration for {Email}", locked.Email.Value);
                return new ConfirmEmailResult { WrongPassword = true, RegistrationToken = encryptedToken };
            }

            var confirmResult = locked.ConfirmEmail(rawToken, utcNow);

            if (confirmResult.IsError)
            {
                if (confirmResult.FirstError.Type != ErrorOr.ErrorType.Conflict)
                {
                    await unitOfWork.RollbackAsync(ct);
                    logger.LogWarning("Email confirmation rejected: invalid or expired token for {Email}", locked.Email.Value);
                    return InvalidConfirmationToken();
                }

                // Email was already confirmed by a previous request.
                return await RecordAlreadyConfirmedAsync(locked, utcNow, ct);
            }

            return await PersistEmailConfirmationAsync(locked, utcNow, ct);
        }
        catch
        {
            await unitOfWork.RollbackAsync(ct);
            throw;
        }
    }

    /// <summary>The answer to a confirmation link that is invalid, expired or superseded, or whose account is gone.</summary>
    private static ConfirmEmailResult InvalidConfirmationToken() => new() { InvalidToken = true, AccountCreated = false };

    /// <summary>Records on the locked row that the address was confirmed before, and ends the transaction of <see cref="ConfirmEmailAsync"/>.</summary>
    private async Task<ConfirmEmailResult> RecordAlreadyConfirmedAsync(Account locked, DateTime utcNow, CancellationToken ct)
    {
        locked.SetMessage(AccountMessage.UserAlreadyCreated.GetDescription(), utcNow);
        try
        {
            await accountRepository.UpdateMessageAsync(locked.Email.Value, locked.Message, locked.Updated, ct);
            await unitOfWork.CommitAsync(ct);
        }
        catch (Exception e)
        {
            logger.LogError(e, "Failed to update account status for {Email}", locked.Email.Value);
            await unitOfWork.RollbackAsync(ct);
        }
        return new ConfirmEmailResult { InvalidToken = false, AccountCreated = false };
    }

    /// <summary>Writes the confirmation of the locked row, and ends the transaction of <see cref="ConfirmEmailAsync"/>.</summary>
    private async Task<ConfirmEmailResult> PersistEmailConfirmationAsync(Account locked, DateTime utcNow, CancellationToken ct)
    {
        locked.SetMessage(AccountMessage.Success.GetDescription(), utcNow);
        int rowsAffected;
        try
        {
            rowsAffected = await accountRepository.UpdateEmailConfirmationAsync(
                locked.Email.Value, locked.RegistrationToken, locked.Message, locked.Updated, ct);
            await unitOfWork.CommitAsync(ct);
        }
        catch (Exception e)
        {
            logger.LogError(e, "Failed to confirm email for account {Email}", locked.Email.Value);
            await unitOfWork.RollbackAsync(ct);
            return new ConfirmEmailResult
            {
                InvalidToken = true,
                AccountCreated = true,
                ErrorKey = ServiceErrorKeys.ConfirmEmailFailed
            };
        }

        // ExecuteUpdateAsync doesn't throw on a missing row -- it just matches zero rows. If the
        // account was deleted concurrently, nothing was actually persisted; report it the same
        // way as "account not found" rather than a false AccountCreated success.
        if (rowsAffected != 0)
        {
            logger.LogInformation("Email confirmed for {Email}", locked.Email.Value);
            return new ConfirmEmailResult { InvalidToken = false, AccountCreated = true };
        }

        logger.LogWarning(
            "Account {Email} no longer existed when its email confirmation was written", locked.Email.Value);
        return InvalidConfirmationToken();
    }

    /// <summary>
    /// Unlocked lookup of the account holding <paramref name="token"/> (raw, already decrypted) as its registration token:
    /// the row stores only <see cref="GuidToken.Hash"/> of it, so that is what is searched for.
    /// </summary>
    private Task<Account?> FindByRegistrationTokenAsync(string token, CancellationToken ct = default)
        => accountRepository.FindByRegistrationTokenAsync(GuidToken.Hash(token), ct);

    /// <summary>
    /// Builds and publishes a registration-confirmation email for <paramref name="account"/>, then
    /// persists its outcome: on publish failure, marks <see cref="AccountMessage.FailToMailSent"/>
    /// and returns a failure result; on success, marks <see cref="AccountMessage.VerifyEmail"/>
    /// (unless <paramref name="setVerifyEmailMessageOnSuccess"/> is false — the newly-created-account
    /// caller already set a more specific message and doesn't need it overwritten) before returning
    /// a success result. Shared by <see cref="RegisterAsync"/> (both branches) and
    /// <see cref="ResendConfirmationEmailAsync"/>, which otherwise repeated this send/persist/report
    /// sequence three times with the same failure modes to keep in sync. <paramref name="registrationToken"/> is the token
    /// the mail carries; the account holds only its hash.
    /// </summary>
    private async Task<RegisterResult> SendConfirmationEmailAndUpdateStatusAsync(
        Account account, string registrationToken, EmailTemplate emailTemplate,
        bool setVerifyEmailMessageOnSuccess, bool repeat, DateTime utcNow, CancellationToken ct)
    {
        // Persist the just-minted registration token's hash BEFORE the mail goes out, so a
        // link that reaches the user always corresponds to a token FindByRegistrationTokenAsync can
        // match. Emailing first and persisting after — inside a swallow-and-log catch — can queue a
        // mail carrying a token the database never stored, leaving the account permanently
        // un-confirmable. Same persist-first rule ForgotPasswordAsync was restructured to follow.
        // (Brand-new-account callers already persisted it via CreateAsync; this write is then a
        // harmless idempotent re-set of the same value.)
        try
        {
            await accountRepository.UpdateRegistrationTokenAsync(
                account.Email.Value, account.RegistrationToken, account.Updated, ct);
        }
        catch (Exception e)
        {
            logger.LogError(e, "Failed to persist registration token for {Email}", account.Email.Value);
            return RegisterResult.Fail(ServiceErrorKeys.AccountStatusFailed);
        }

        string body;
        try
        {
            body = mailClient.GetMailConfirmationBody(dataProtection.Protect(ProtectedValue.MailToken, registrationToken), emailTemplate.Title, emailTemplate.Content0, emailTemplate.Content1, settings.Value.DomainName ?? "");
        }
        catch (Exception e)
        {
            logger.LogError(e, "Failed to build confirmation mail body for {Email}", account.Email.Value);
            return RegisterResult.Fail(ServiceErrorKeys.AuthenticationMailFailed);
        }

        bool published = await emailPublisher.TryPublishAsync(logger, account.Email.Value, emailTemplate.Subject, body, ct);

        if (!published)
        {
            try
            {
                account.SetMessage(AccountMessage.FailToMailSent.GetDescription(), utcNow);
                await accountRepository.UpdateMessageAsync(account.Email.Value, account.Message, account.Updated, ct);
            }
            catch (Exception e) { logger.LogWarning(e, "Failed to update account message after mail send failure for {Email}", account.Email.Value); }
            return RegisterResult.Fail(ServiceErrorKeys.AuthenticationMailFailed);
        }

        if (!setVerifyEmailMessageOnSuccess)
        {
            return RegisterResult.Ok(showResendEmail: true, email: account.Email.Value, repeat: repeat);
        }

        {
            try
            {
                account.SetMessage(AccountMessage.VerifyEmail.GetDescription(), utcNow);
                await accountRepository.UpdateMessageAsync(account.Email.Value, account.Message, account.Updated, ct);
            }
            catch (Exception e)
            {
                logger.LogError(e, "Failed to update account status for {Email}", account.Email.Value);
                return RegisterResult.Fail(ServiceErrorKeys.AccountStatusFailed);
            }
        }

        return RegisterResult.Ok(showResendEmail: true, email: account.Email.Value, repeat: repeat);
    }
}
