namespace Maroik.Core.Service.Services;

/// <summary>
/// Implementation of <see cref="IAccountService"/> handling all self-service account flows:
/// login, registration, email confirmation, and password reset.
/// Login passwords are verified with BCrypt (<see cref="IPasswordService"/>); the RSA service
/// is used only to encrypt/decrypt the tokens embedded in confirmation and password-reset links.
/// Registration and password-reset tokens are generated by <see cref="GuidToken"/>.
/// Email bodies are built via <see cref="IMailClient"/> and handed off to <see cref="IEmailPublisher"/>,
/// which enqueues them for asynchronous SMTP delivery by Maroik.Worker instead of sending inline.
/// Accounts are locked after excessive failed login attempts (threshold from <see cref="ServerSetting"/>).
/// </summary>
public class AccountService : IAccountService
{
    private readonly IAccountRepository _accountRepository;
    private readonly IPasswordService _passwordService;
    private readonly IMailClient _mailClient;
    private readonly IEmailPublisher _emailPublisher;
    private readonly IRsaService _rsa;
    private readonly IOptions<ServerSetting> _settings;
    private readonly ILogger<AccountService> _logger;
    private readonly IUnitOfWork _unitOfWork;

    /// <summary>Initializes a new instance of <see cref="AccountService"/> with the supplied dependencies.</summary>
    public AccountService(
        IAccountRepository accountRepository,
        IPasswordService passwordService,
        IMailClient mailClient,
        IEmailPublisher emailPublisher,
        IOptions<ServerSetting> settings,
        IRsaService rsa,
        ILogger<AccountService> logger,
        IUnitOfWork unitOfWork)
    {
        _accountRepository = accountRepository;
        _passwordService = passwordService;
        _mailClient = mailClient;
        _emailPublisher = emailPublisher;
        _settings = settings;
        _rsa = rsa;
        _logger = logger;
        _unitOfWork = unitOfWork;
    }

    /// <inheritdoc />
    public async Task<List<AccountResponse>> GetAllAccountsAsync(CancellationToken ct = default)
        => (await _accountRepository.GetAllAsync(ct)).Select(AccountMapper.ToResponse).ToList();

    /// <inheritdoc />
    public async Task<List<AccountResponse>> GetAccountsByNicknamesAsync(IEnumerable<string> nicknames, CancellationToken ct = default)
        => (await _accountRepository.FindByNicknamesAsync(nicknames, ct)).Select(AccountMapper.ToResponse).ToList();

    /// <inheritdoc />
    public async Task<AccountResponse?> GetAccountByEmailAsync(string email, CancellationToken ct = default)
    {
        Account? account = await FindByEmailAsync(email, ct);
        return account == null ? null : AccountMapper.ToResponse(account);
    }

    /// <inheritdoc />
    public async Task<LoginResult> LoginAsync(string email, string password, CancellationToken ct = default)
    {
        await _unitOfWork.BeginAsync(ct);
        try
        {
            // Row lock (FOR UPDATE) held until commit/rollback below, so concurrent login attempts
            // against the same account are fully serialized: each one sees the latest committed
            // LoginAttempt/Locked state rather than a stale pre-lock read.
            Account? account = await _accountRepository.FindByEmailForUpdateAsync(email, ct);

            const string genericLoginError = "Email or Password is wrong";

            if (account == null)
            {
                // Spend the same CPU as a real verification so "no such account" and "wrong
                // password" take the same time — otherwise the response time enumerates valid emails.
                _passwordService.VerifyDummy(password);
                // ...and issue an equivalent (0-row) column write + commit so this path's DB cost
                // matches the wrong-password path below (which persists the failed-attempt counter),
                // instead of returning early after a bare rollback.
                _ = await _accountRepository.UpdateMessageAsync(email, null, DateTime.UtcNow, ct);
                await _unitOfWork.CommitAsync(ct);
                return LoginResult.Fail(genericLoginError);
            }

            // Verify the password FIRST, for every account regardless of its state. The account-state
            // messages below (deleted / locked / unconfirmed / terms) are only disclosed to a caller
            // that has proven it owns the account, so a wrong password can no longer be used to probe
            // whether an email exists or what state it is in — every wrong guess returns the same
            // generic error.
            if (!_passwordService.VerifyPassword(password, account.HashedPassword))
            {
                account.RecordLoginFailure(_settings.Value.MaxLoginAttempt);
                await _accountRepository.UpdateEntityAsync(account, ct);
                await _unitOfWork.CommitAsync(ct);
                return LoginResult.Fail(genericLoginError);
            }

            if (account.Deleted)
            {
                await _unitOfWork.RollbackAsync(ct);
                return LoginResult.Fail("Your Account is Deleted, Please create your new account by clicking Sign up Button");
            }

            if (account.Locked)
            {
                await _unitOfWork.RollbackAsync(ct);
                return LoginResult.Fail("Your Account is Locked, Please reset your password by clicking Forgot password Button");
            }

            if (!account.EmailConfirmed)
            {
                await _unitOfWork.RollbackAsync(ct);
                return LoginResult.Fail("Email verification was not completed. Please try sign up again.");
            }

            if (!account.AgreedServiceTerms)
            {
                await _unitOfWork.RollbackAsync(ct);
                return LoginResult.Fail("Agreed Service Terms was not checked. Please try sign up again and login again.");
            }

            // Successful login: clear any prior failed attempt counter.
            account.ResetLoginAttempt();
            await _accountRepository.UpdateEntityAsync(account, ct);
            await _unitOfWork.CommitAsync(ct);

            return LoginResult.Ok(AccountMapper.ToResponse(account));
        }
        catch
        {
            await _unitOfWork.RollbackAsync(ct);
            throw;
        }
    }

    /// <inheritdoc />
    public async Task<RegisterResult> RegisterAsync(AccountRequest newAccount, EmailTemplate emailTemplate, CancellationToken ct = default)
    {
        Account? existing = await FindByEmailAsync(newAccount.Email ?? "", ct);

        if (existing == null)
        {
            // Enforce the password-complexity rule at the service boundary (not just the ViewModel),
            // before hashing — Account.Create only ever sees the already-hashed value.
            if (!PasswordPolicy.IsValid(newAccount.PlainPassword))
                return RegisterResult.Fail(PasswordPolicy.ViolationMessage);

            // Brand-new account: hash the plain-text password and create the domain entity.
            string hashedPassword = _passwordService.HashPassword(newAccount.PlainPassword ?? "");

            var createResult = Account.Create(
                newAccount.Email ?? "",
                hashedPassword,
                newAccount.Nickname ?? "",
                newAccount.Role ?? Role.User,
                newAccount.TimeZoneIanaId ?? "UTC",
                newAccount.DefaultMonetaryUnit,
                newAccount.RegistrationToken,
                newAccount.AgreedServiceTerms);

            if (createResult.IsError)
                return RegisterResult.Fail(createResult.FirstError.Description);

            var account = createResult.Value;
            account.SetMessage(EnumHelper.GetDescription(AccountMessage.UserCreatedVerifyEmail));

            try
            {
                await _accountRepository.CreateAsync(account, ct);
            }
            catch (Exception e)
            {
                if (e.IsPostgresUniqueViolation())
                {
                    // The prior FindByEmailAsync check above is a read-then-write race: two concurrent
                    // registrations for the same not-yet-registered email can both pass it. Email is the
                    // actual primary key (Account_pk), while Nickname has its own separate unique
                    // constraint (Account_Nickname_unique) — report whichever one actually collided
                    // instead of always blaming the nickname.
                    bool isNicknameConflict = e.InnerException?.Message.Contains("Account_Nickname_unique", StringComparison.Ordinal) ?? false;
                    return isNicknameConflict
                        ? RegisterResult.Fail($"'{newAccount.Nickname}' is a Nickname that already exists. Please enter another Nickname.")
                        : RegisterResult.Fail($"'{newAccount.Email}' is an Email that already exists.");
                }
                _logger.LogError(e, "Failed to create account for {Email}", newAccount.Email);
                return RegisterResult.Fail("Error occurred while processing about account registration");
            }

            // The account was just created with UserCreatedVerifyEmail already set above, so a
            // successful send should not overwrite it with VerifyEmail.
            return await SendConfirmationEmailAndUpdateStatusAsync(
                account, emailTemplate,
                setVerifyEmailMessageOnSuccess: false, repeat: false, ct);
        }

        if (!existing.EmailConfirmed)
        {
            // Account exists but email was never confirmed: regenerate the token when it is missing
            // OR has passed its 24h TTL, so a stale registration is always recoverable by re-registering.
            if (string.IsNullOrEmpty(existing.RegistrationToken) || !GuidToken.IsTokenAlive(existing.RegistrationToken))
                existing.RegenerateRegistrationToken(GuidToken.Generate());

            return await SendConfirmationEmailAndUpdateStatusAsync(
                existing, emailTemplate,
                setVerifyEmailMessageOnSuccess: true, repeat: false, ct);
        }

        // Account is fully confirmed: tell the caller it already exists and bring the account's own
        // stored status into line — but write a column only when its value would actually change.
        // This path runs off an un-locked FindByEmailAsync read against another user's row from an
        // unauthenticated request, so it must NOT use the full-row UpdateEntityAsync (it would
        // revert a concurrent self-service change from the stale snapshot), and a no-op must stay a
        // no-op: an email-enumerating caller must not be able to churn a stranger's Updated
        // timestamp by replaying this endpoint. Column-scoped writes only, like every other Account
        // write path.
        string alreadyCreatedMessage = EnumHelper.GetDescription(AccountMessage.UserAlreadyCreated);
        try
        {
            if (!existing.AgreedServiceTerms)
            {
                existing.AcceptServiceTerms();
                await _accountRepository.UpdateAgreedServiceTermsAsync(
                    existing.Email.Value, existing.AgreedServiceTerms, existing.Updated, ct);
            }

            if (!string.Equals(existing.Message, alreadyCreatedMessage, StringComparison.Ordinal))
            {
                existing.SetMessage(alreadyCreatedMessage);
                await _accountRepository.UpdateMessageAsync(
                    existing.Email.Value, existing.Message, existing.Updated, ct);
            }
        }
        catch (Exception e)
        {
            _logger.LogError(e, "Failed to update account status for {Email}", existing.Email.Value);
            return RegisterResult.Fail("Error occurred while processing about account status");
        }

        return RegisterResult.Fail(alreadyCreatedMessage);
    }

    /// <inheritdoc />
    public async Task<RegisterResult> ResendConfirmationEmailAsync(string email, EmailTemplate emailTemplate, CancellationToken ct = default)
    {
        Account? account = await FindByEmailAsync(email, ct);
        if (account == null)
            return RegisterResult.Fail("Failed to resend email", showResendEmail: true);

        if (!account.EmailConfirmed)
        {
            // Ensure a live token exists before building the confirmation URL — regenerate when it is
            // missing OR has passed its 24h TTL (otherwise a resend just re-sends a dead link).
            if (string.IsNullOrEmpty(account.RegistrationToken) || !GuidToken.IsTokenAlive(account.RegistrationToken))
                account.RegenerateRegistrationToken(GuidToken.Generate());

            // repeat: true signals the UI that this is a resend, not the first confirmation.
            return await SendConfirmationEmailAndUpdateStatusAsync(
                account, emailTemplate,
                setVerifyEmailMessageOnSuccess: true, repeat: true, ct);
        }

        // Email is already confirmed: inform the caller the account is fully created. Column-scoped
        // write (not full-row UpdateEntityAsync) — this path runs off an un-locked read and must not
        // clobber a concurrent self-service change on the same row — and skip the write entirely
        // when the stored message already says this, so replaying this endpoint against a known
        // address cannot churn a stranger's Updated timestamp.
        string alreadyCreatedMessage = EnumHelper.GetDescription(AccountMessage.UserAlreadyCreated);
        try
        {
            if (!string.Equals(account.Message, alreadyCreatedMessage, StringComparison.Ordinal))
            {
                account.SetMessage(alreadyCreatedMessage);
                await _accountRepository.UpdateMessageAsync(account.Email.Value, account.Message, account.Updated, ct);
            }
        }
        catch (Exception e)
        {
            _logger.LogError(e, "Failed to update account status for {Email}", email);
            return RegisterResult.Fail("Error occurred while processing about account status");
        }

        return RegisterResult.Fail(alreadyCreatedMessage);
    }

    /// <inheritdoc />
    public async Task<ConfirmEmailResult> ConfirmEmailAsync(string encryptedToken, CancellationToken ct = default)
    {
        string rawToken;
        try { rawToken = _rsa.Decrypt(encryptedToken); }
        catch (Exception e)
        {
            _logger.LogWarning(e, "Failed to decrypt registration token");
            return new ConfirmEmailResult { InvalidToken = true, AccountCreated = false };
        }

        Account? account = await FindByRegistrationTokenAsync(rawToken, ct);
        if (account == null)
            return new ConfirmEmailResult { InvalidToken = true, AccountCreated = false };

        // Reject tokens that have passed their time-to-live window.
        if (!GuidToken.IsTokenAlive(rawToken))
            return new ConfirmEmailResult { InvalidToken = true, AccountCreated = false };

        // account was already looked up by RegistrationToken == rawToken above, so the
        // token check inside ConfirmEmail is redundant here; kept because the domain
        // method enforces its own invariant regardless of how the caller found the account.
        var confirmResult = account.ConfirmEmail(rawToken);

        if (confirmResult.IsError)
        {
            if (confirmResult.FirstError.Type != ErrorOr.ErrorType.Conflict)
            {
                return new ConfirmEmailResult { InvalidToken = true, AccountCreated = true };
            }

            // Email was already confirmed by a previous request. Column-scoped write (not full-row
            // UpdateEntityAsync): this runs off an un-locked token lookup and must not overwrite a
            // concurrent self-service change on the same row.
            account.SetMessage(EnumHelper.GetDescription(AccountMessage.UserAlreadyCreated));
            try { await _accountRepository.UpdateMessageAsync(account.Email.Value, account.Message, account.Updated, ct); }
            catch (Exception e) { _logger.LogError(e, "Failed to update account status for {Email}", account.Email.Value); }
            return new ConfirmEmailResult { InvalidToken = false, AccountCreated = false };
        }

        account.SetMessage(EnumHelper.GetDescription(AccountMessage.Success));
        try
        {
            await _accountRepository.UpdateEntityAsync(account, ct);
        }
        catch (Exception e)
        {
            _logger.LogError(e, "Failed to confirm email for account {Email}", account.Email.Value);
            return new ConfirmEmailResult
            {
                InvalidToken = true,
                AccountCreated = true,
                ErrorKey = "Error occurred while processing about confirm email account status"
            };
        }
        return new ConfirmEmailResult { InvalidToken = false, AccountCreated = true };
    }

    /// <inheritdoc />
    public async Task<bool> ForgotPasswordAsync(string email, EmailTemplate emailTemplate, CancellationToken ct = default)
    {
        Account? account = await FindByEmailAsync(email, ct);

        // Silently succeed even when the email is unknown / unconfirmed to avoid user enumeration.
        // The response body is already identical, but the success path below spends a token
        // generation, an RSA encrypt and two column writes that an early `return true` would skip —
        // a measurable timing oracle for "is this a registered, confirmed address?". Spend the
        // equivalent work here first, mirroring LoginAsync's VerifyDummy + dummy-write hardening.
        // (The async mail publish on the success path is the only residual asymmetry, the same
        // trade-off LoginAsync accepts.)
        if (account == null || !account.EmailConfirmed)
        {
            try
            {
                _ = _rsa.Encrypt(GuidToken.Generate());
                _ = await _accountRepository.UpdateResetPasswordTokenAsync(email, null, DateTime.UtcNow, ct);
            }
            catch (Exception e) { _logger.LogWarning(e, "ForgotPassword equalization failed for {Email}", email); }
            return true;
        }

        string resetPasswordToken = GuidToken.Generate();

        try
        {
            // Persist the reset token FIRST, so any mail that goes out corresponds to a token the
            // database will actually accept. The reverse order can e-mail a link whose token was
            // never saved (mail sent, then the save fails) — a dead link the user cannot use.
            // RequestPasswordReset only errors when EmailConfirmed is false, already ruled out above.
            if (account.RequestPasswordReset(resetPasswordToken).IsError)
                return true;

            // Column-scoped writes (ResetPasswordToken/Message + Updated), not a full-row
            // UpdateEntityAsync: this runs off an un-locked read, so a concurrent self-service
            // profile change (avatar/timezone/password) on the same account must not be reverted by
            // a stale full-row snapshot — same rationale as every other Account write path.
            await _accountRepository.UpdateResetPasswordTokenAsync(
                account.Email.Value, account.ResetPasswordToken, account.Updated, ct);

            string body = _mailClient.GetMailResetPasswordBody(_rsa.Encrypt(resetPasswordToken), emailTemplate.Title, emailTemplate.Content0, emailTemplate.Content1, _settings.Value.DomainName ?? "");
            bool published = await PublishMailAsync(account.Email.Value, emailTemplate.Subject, body, ct);

            account.SetMessage(EnumHelper.GetDescription(published ? AccountMessage.ResetPasswordMail : AccountMessage.FailToMailSent));
            await _accountRepository.UpdateMessageAsync(account.Email.Value, account.Message, account.Updated, ct);
        }
        catch (Exception e) { _logger.LogWarning(e, "ForgotPassword failed for {Email}", email); }

        return true;
    }

    /// <inheritdoc />
    public async Task<ResetPasswordValidationResult> ValidateResetPasswordTokenAsync(string encryptedToken, CancellationToken ct = default)
    {
        string rawToken;
        try { rawToken = _rsa.Decrypt(encryptedToken); }
        catch (Exception e)
        {
            _logger.LogWarning(e, "Failed to decrypt reset password token");
            return new ResetPasswordValidationResult { FailToReset = true };
        }

        Account? account = await FindByResetPasswordTokenAsync(rawToken, ct);

        // Reject if account not found, token has expired, or email is unconfirmed.
        if (account == null || !GuidToken.IsTokenAlive(rawToken) || !account.EmailConfirmed)
            return new ResetPasswordValidationResult { FailToReset = true };

        // Return the still-encrypted token so the client can pass it back during the actual reset.
        return new ResetPasswordValidationResult { FailToReset = false, ResetPasswordToken = encryptedToken };
    }

    /// <inheritdoc />
    public async Task<ServiceResult> ResetPasswordAsync(string encryptedToken, string newPassword, CancellationToken ct = default)
    {
        string rawToken;
        try { rawToken = _rsa.Decrypt(encryptedToken); }
        catch (Exception e)
        {
            _logger.LogWarning(e, "Failed to decrypt reset password token");
            return ServiceResult.Fail("reset-password-invalid");
        }

        Account? found = await FindByResetPasswordTokenAsync(rawToken, ct);
        if (found == null || !GuidToken.IsTokenAlive(rawToken) || !found.EmailConfirmed)
            return ServiceResult.Fail("reset-password-invalid");

        // Enforce the complexity rule server-side, before hashing — Account.ResetPassword only sees the hash.
        if (!PasswordPolicy.IsValid(newPassword))
            return ServiceResult.Validation("Account.PasswordPolicy", PasswordPolicy.ViolationMessage);

        string newHashedPassword = _passwordService.HashPassword(newPassword);

        await _unitOfWork.BeginAsync(ct);
        try
        {
            // The lookup above was by token and unlocked. Re-read the row under FOR UPDATE before
            // writing: this touches HashedPassword / SecurityStamp / Locked, so it must not run as a
            // stale full-row overwrite that reverts a concurrent self-service change on the same
            // account (the user may be signed in on another device).
            Account? account = await _accountRepository.FindByEmailForUpdateAsync(found.Email.Value, ct);
            if (account == null)
            {
                await _unitOfWork.RollbackAsync(ct);
                return ServiceResult.Fail("reset-password-invalid");
            }

            // ResetPassword re-checks the stored token, so a concurrent reset that already consumed
            // it between the lookup and this lock is rejected here (compare-and-swap).
            var resetResult = account.ResetPassword(rawToken, newHashedPassword);
            if (resetResult.IsError)
            {
                await _unitOfWork.RollbackAsync(ct);
                return ServiceResult.Fail("reset-password-invalid");
            }

            // Unlock the account so the user can log in immediately after resetting their password.
            account.Unlock();
            account.SetMessage(EnumHelper.GetDescription(AccountMessage.SuccessToResetPassword));

            await _accountRepository.UpdateEntityAsync(account, ct);
            await _unitOfWork.CommitAsync(ct);
            return ServiceResult.Ok();
        }
        catch (Exception e)
        {
            _logger.LogError(e, "Failed to reset password for {Email}", found.Email.Value);
            await _unitOfWork.RollbackAsync(ct);
            return ServiceResult.Failure("Account.ResetPasswordFailed", "Error occurred while processing about reset password");
        }
    }

    private Task<Account?> FindByEmailAsync(string email, CancellationToken ct = default)
        => _accountRepository.FindByEmailAsync(email, ct);

    private Task<Account?> FindByRegistrationTokenAsync(string token, CancellationToken ct = default)
        => _accountRepository.FindByRegistrationTokenAsync(token, ct);

    private Task<Account?> FindByResetPasswordTokenAsync(string token, CancellationToken ct = default)
        => _accountRepository.FindByResetPasswordTokenAsync(token, ct);

    /// <summary>
    /// Builds and publishes a registration-confirmation email for <paramref name="account"/>, then
    /// persists its outcome: on publish failure, marks <see cref="AccountMessage.FailToMailSent"/>
    /// and returns a failure result; on success, marks <see cref="AccountMessage.VerifyEmail"/>
    /// (unless <paramref name="setVerifyEmailMessageOnSuccess"/> is false — the newly-created-account
    /// caller already set a more specific message and doesn't need it overwritten) before returning
    /// a success result. Shared by <see cref="RegisterAsync"/> (both branches) and
    /// <see cref="ResendConfirmationEmailAsync"/>, which otherwise repeated this send/persist/report
    /// sequence three times with the same failure modes to keep in sync.
    /// </summary>
    private async Task<RegisterResult> SendConfirmationEmailAndUpdateStatusAsync(
        Account account, EmailTemplate emailTemplate,
        bool setVerifyEmailMessageOnSuccess, bool repeat, CancellationToken ct)
    {
        // Persist the (possibly just-regenerated) registration token BEFORE the mail goes out, so a
        // link that reaches the user always corresponds to a token FindByRegistrationTokenAsync can
        // match. Emailing first and persisting after — inside a swallow-and-log catch — can queue a
        // mail carrying a token the database never stored, leaving the account permanently
        // un-confirmable. Same persist-first rule ForgotPasswordAsync was restructured to follow.
        // (Brand-new-account callers already persisted it via CreateAsync; this write is then a
        // harmless idempotent re-set of the same value.)
        try
        {
            await _accountRepository.UpdateRegistrationTokenAsync(
                account.Email.Value, account.RegistrationToken, account.Updated, ct);
        }
        catch (Exception e)
        {
            _logger.LogError(e, "Failed to persist registration token for {Email}", account.Email.Value);
            return RegisterResult.Fail("Error occurred while processing about account status");
        }

        string body = _mailClient.GetMailConfirmationBody(_rsa.Encrypt(account.RegistrationToken!), emailTemplate.Title, emailTemplate.Content0, emailTemplate.Content1, _settings.Value.DomainName ?? "");
        bool published = await PublishMailAsync(account.Email.Value, emailTemplate.Subject, body, ct);

        if (!published)
        {
            try
            {
                account.SetMessage(EnumHelper.GetDescription(AccountMessage.FailToMailSent));
                await _accountRepository.UpdateMessageAsync(account.Email.Value, account.Message, account.Updated, ct);
            }
            catch (Exception e) { _logger.LogWarning(e, "Failed to update account message after mail send failure for {Email}", account.Email.Value); }
            return RegisterResult.Fail("Error occurred while processing about sending account authentication mail");
        }

        if (setVerifyEmailMessageOnSuccess)
        {
            try
            {
                account.SetMessage(EnumHelper.GetDescription(AccountMessage.VerifyEmail));
                await _accountRepository.UpdateMessageAsync(account.Email.Value, account.Message, account.Updated, ct);
            }
            catch (Exception e)
            {
                _logger.LogError(e, "Failed to update account status for {Email}", account.Email.Value);
                return RegisterResult.Fail("Error occurred while processing about account status");
            }
        }

        return RegisterResult.Ok(showResendEmail: true, email: account.Email.Value, repeat: repeat);
    }

    /// <summary>
    /// Enqueues a mail via <see cref="IEmailPublisher"/> for asynchronous delivery by Maroik.Worker.
    /// Returns <see langword="true"/> once the message has been accepted by the queue, or
    /// <see langword="false"/> if publishing itself failed (e.g. RabbitMQ unreachable).
    /// </summary>
    private async Task<bool> PublishMailAsync(string to, string subject, string body, CancellationToken ct = default)
    {
        var correlationId = Activity.Current?.Id ?? "";
        try
        {
#pragma warning disable CA1873
            _logger.LogInformation("Publishing email to {Email}. CorrelationId={CorrelationId}", to, correlationId);
#pragma warning restore CA1873
            await _emailPublisher.PublishAsync(new SendEmailMessage(to, subject, body, correlationId), ct);
            return true;
        }
        catch (Exception e)
        {
            _logger.LogError(e, "Failed to publish email message for {Email}", to);
            return false;
        }
    }
}
