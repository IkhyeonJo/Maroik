namespace Maroik.Core.Contract.Tokens;

/// <summary>
/// Utility class for generating and validating time-stamped tokens used in
/// email confirmation and password-reset flows. Tokens expire after 24 hours.
/// </summary>
public class GuidToken
{
    /// <summary>
    /// Generates a Base64-encoded token that embeds the current UTC timestamp
    /// followed by a random GUID. The timestamp allows expiry checking via <see cref="IsTokenAlive"/>.
    /// </summary>
    /// <returns>A URL-safe Base64 token string.</returns>
    public static string Generate()
    {
        #region Unique token

        //string token = Convert.ToBase64String(Guid.NewGuid().ToByteArray());

        #endregion

        #region Basic example of creating a unique token containing a time stamp: https: //stackoverflow.com/questions/14643735/how-to-generate-a-unique-token-which-expires-after-24-hours

        // Embed the current UTC time so we can check expiry later
        byte[] time = BitConverter.GetBytes(DateTime.UtcNow.ToBinary());
        // Append a random GUID to make the token unique and unguessable
        byte[] key = Guid.NewGuid().ToByteArray();
        string token = Convert.ToBase64String(time.Concat(key).ToArray());

        #endregion

        return token;
    }

    /// <summary>
    /// Checks whether a token generated by <see cref="Generate"/> is still within its 24-hour validity window.
    /// </summary>
    /// <param name="token">The Base64 token to validate.</param>
    /// <returns>True if the token was created less than 24 hours ago; false if expired or malformed.</returns>
    public static bool IsTokenAlive(string token)
    {
        // Decode and extract the UTC creation timestamp from the first 8 bytes
        byte[] data = Convert.FromBase64String(token);
        DateTime when = DateTime.FromBinary(BitConverter.ToInt64(data, 0));

        if (when < DateTime.UtcNow.AddHours(-24))
        {
            return false; // token has expired
        }
        else
        {
            return true; // token is still valid
        }
    }
}
